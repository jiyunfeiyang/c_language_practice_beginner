/* ===================== 日期 / 儒略日 ===================== */
static bool isLeapYear(int y)
{
    return (y % 4 == 0 && y % 100 != 0) || (y % 400 == 0);
}

static int daysInMonth(int y, int m)
{
    static const int D[13] = {0, 31, 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31};
    if (m == 2 && isLeapYear(y)) return 29;
    return D[m];
}

/* 儒略日：返回该日正午的儒略日数（与寿星天文历一致） */
static long toJDN(int y, int m, int d)
{
    int a = (14 - m) / 12;
    long yy = y + 4800 - a;
    long mm = m + 12 * a - 3;
    return d + (153 * mm + 2) / 5 + 365 * yy + yy / 4 - yy / 100 + yy / 400 - 32045;
}

static void fromJDN(long jdn, int &y, int &m, int &d)
{
    long a = jdn + 32044;
    long b = (4 * a + 3) / 146097;
    long c = a - 146097 * b / 4;
    long dd = (4 * c + 3) / 1461;
    long e = c - 1461 * dd / 4;
    long mm = (5 * e + 2) / 153;
    d = (int)(e - (153 * mm + 2) / 5 + 1);
    m = (int)(mm + 3 - 12 * (mm / 10));
    y = (int)(100 * b + dd - 4800 + mm / 10);
}

/* 把时刻换算成一个可直接比较的整数：儒略日 * 86400 + 当日秒数 */
static long long momentOf(int y, int m, int d, int h, int mi, int s)
{
    return (long long)toJDN(y, m, d) * 86400LL + (long long)h * 3600LL + mi * 60LL + s;
}

/* ===================== 农历换算 ===================== */
static int lunarLeapMonth(int y) { return (int)(LUNAR_INFO[y - 1899] & 0xf); }
static int lunarLeapDays(int y)  { return (LUNAR_INFO[y - 1899] & 0x10000L) ? 30 : 29; }
static int lunarMonthDays(int y, int m) { return (LUNAR_INFO[y - 1899] & (0x10000L >> m)) ? 30 : 29; }

static int lunarYearDays(int y)
{
    long info = LUNAR_INFO[y - 1899];
    int sum = 348;                         /* 12 个月先按 29 天算 */
    for (long i = 0x8000; i > 0x8; i >>= 1)
        if (info & i) ++sum;               /* 该位为 1 表示这个月 30 天 */
    if (lunarLeapMonth(y) > 0) sum += lunarLeapDays(y);
    return sum;
}

/* 阳历 -> 农历；lunarMonth 为负表示闰月 */
static bool solarToLunar(int y, int m, int d, int &ly, int &lm, int &ld)
{
    long off = toJDN(y, m, d) - toJDN(1900, 1, 31);   /* 1900-01-31 是农历 1900 年正月初一 */
    int yy = 1900;
    while (off >= lunarYearDays(yy)) { off -= lunarYearDays(yy); ++yy; if (yy > 2101) return false; }
    while (off < 0) { --yy; off += lunarYearDays(yy); }

    int leap = lunarLeapMonth(yy);
    int mm = 1;
    bool isLeap = false;
    while (true)
    {
        int len = isLeap ? lunarLeapDays(yy) : lunarMonthDays(yy, mm);
        if (off < len) break;
        off -= len;
        if (!isLeap && leap > 0 && mm == leap) isLeap = true;   /* 闰月紧跟同月之后 */
        else { if (isLeap) isLeap = false; ++mm; }
    }
    ly = yy;
    lm = isLeap ? -mm : mm;
    ld = (int)off + 1;
    return true;
}

/* ===================== 干支 / 十神 ===================== */
/* 由天干、地支序号求六十甲子序号（0=甲子） */
static int gzIndexOf(int stem, int branch)
{
    int i = (6 * stem - 5 * branch) % 60;
    if (i < 0) i += 60;
    return i;
}

static string gzName(int gz)
{
    string s = GAN_NAME[gz % 10];
    s += ZHI_NAME[gz % 12];
    return s;
}

/* 十神：dayStem 为日主，target 为要判断的天干 */
static int shiShenOf(int dayStem, int target)
{
    int de = dayStem / 2;                 /* 五行：0木 1火 2土 3金 4水 */
    int te = target / 2;
    int diff = (te - de + 5) % 5;         /* 0同我 1我生 2我克 3克我 4生我 */
    bool same = ((dayStem % 2) == (target % 2));
    return diff * 2 + (same ? 0 : 1);
}

/* 时辰序号：23:00~00:59 为子时(0)，01:00~02:59 为丑时(1) …… */
static int timeZhiIndex(int h) { return ((h + 1) / 2) % 12; }

/* ===================== 排盘结果 ===================== */
struct Moment
{
    int y, m, d, h, mi, s;
    long long t;
};

struct Chart
{
    int y, mo, d, h, mi;            /* 阳历生日 */
    int lunarYear, lunarMonth, lunarDay;
    int gzYear;                     /* 八字用的年（以立春换年） */
    int shengXiao;
    int yearGZ, monthGZ, dayGZ, timeGZ;
    int dayStem, dayBranch, timeStem, timeBranch;
    int shiShenGan[3];              /* 年干、月干、时干 的十神 */
    int hideGan[4][4], hideCount[4], shiShenZhi[4][4];
    int naYin[4];
    int xunKong[4][2];
    int wuXing[5];                  /* 五行个数（天干 + 藏干） */
    int jieIndex;                   /* 当前所处的「节」0=小寒 …… 11=大雪 */
    Moment curJie, nextJie;
    bool hasYun, forward;
    int startYear, startMonth, startDay, startHour, startSolarYear;
    int daYunGZ[10], daYunAge[10];
    bool lateZi;                    /* 是否为晚子时(23:00~23:59) */
};

/* 取第 year 年第 k 个「节」（k=0 小寒，落在 1 月；k=11 大雪，落在 12 月） */
static Moment getJie(int year, int k)
{
    Moment mo;
    long v = JIE_SEC[year - 1899][k];
    mo.d = (int)(v / 86400) + 1;
    long rest = v % 86400;
    mo.h = (int)(rest / 3600);
    mo.mi = (int)((rest % 3600) / 60);
    mo.s = (int)(rest % 60);
    mo.m = k + 1;
    mo.y = year;
    mo.t = momentOf(mo.y, mo.m, mo.d, mo.h, mo.mi, mo.s);
    return mo;
}

static bool buildChart(int y, int mo, int d, int h, int mi, int gender, Chart &c)
{
    if (y < 1900 || y > 2100) return false;
    if (mo < 1 || mo > 12) return false;
    if (d < 1 || d > daysInMonth(y, mo)) return false;
    if (h < 0 || h > 23 || mi < 0 || mi > 59) return false;

    c.y = y; c.mo = mo; c.d = d; c.h = h; c.mi = mi;

    /* ---- 农历 ---- */
    if (!solarToLunar(y, mo, d, c.lunarYear, c.lunarMonth, c.lunarDay)) return false;
    c.shengXiao = ((c.lunarYear - 4) % 12 + 12) % 12;

    long long birth = momentOf(y, mo, d, h, mi, 0);

    /* ---- 年柱：立春精确时刻换年 ---- */
    Moment lichun = getJie(y, 1);
    int gzYear = (birth < lichun.t) ? y - 1 : y;
    c.gzYear = gzYear;
    c.yearGZ = ((gzYear - 4) % 60 + 60) % 60;
    int yearStem = c.yearGZ % 10;

    /* ---- 月柱：找出生时刻之前最近的一个「节」 ---- */
    Moment prev, next;
    bool hasPrev = false, hasNext = false;
    for (int yy = y - 1; yy <= y + 1; ++yy)
    {
        if (yy < 1899 || yy > 2101) continue;
        for (int k = 0; k < 12; ++k)
        {
            Moment j = getJie(yy, k);
            if (j.t <= birth) { if (!hasPrev || j.t > prev.t) { prev = j; hasPrev = true; } }
            else              { if (!hasNext || j.t < next.t) { next = j; hasNext = true; } }
        }
    }
    if (!hasPrev || !hasNext) return false;
    c.curJie = prev;
    c.nextJie = next;
    c.jieIndex = prev.m - 1;                       /* 小寒->0 …… 大雪->11 */

    int monthBranch = (c.jieIndex + 1) % 12;       /* 小寒=丑月, 立春=寅月 …… */
    int offset = (c.jieIndex - 1 + 12) % 12;       /* 距寅月的月数 */
    int monthStem = ((yearStem % 5) * 2 + 2 + offset) % 10;   /* 五虎遁 */
    c.monthGZ = gzIndexOf(monthStem, monthBranch);

    /* ---- 日柱：儒略日推算 ---- */
    long jdn = toJDN(y, mo, d);
    int o = (int)((jdn - 11) % 60);
    c.dayStem = ((o % 10) + 10) % 10;
    c.dayBranch = ((o % 12) + 12) % 12;
    c.dayGZ = gzIndexOf(c.dayStem, c.dayBranch);

    /* ---- 时柱：五鼠遁（晚子时用次日的日干起子时） ---- */
    c.lateZi = (h == 23);
    c.timeBranch = timeZhiIndex(h);
    int stemForTime = c.lateZi ? (c.dayStem + 1) % 10 : c.dayStem;
    c.timeStem = ((stemForTime % 5) * 2 + c.timeBranch) % 10;
    c.timeGZ = gzIndexOf(c.timeStem, c.timeBranch);

    /* ---- 十神 ---- */
    c.shiShenGan[0] = shiShenOf(c.dayStem, c.yearGZ % 10);
    c.shiShenGan[1] = shiShenOf(c.dayStem, monthStem);
    c.shiShenGan[2] = shiShenOf(c.dayStem, c.timeStem);

    /* ---- 藏干与藏干十神、纳音、空亡、五行统计 ---- */
    int branches[4];
    branches[0] = c.yearGZ % 12;
    branches[1] = monthBranch;
    branches[2] = c.dayBranch;
    branches[3] = c.timeBranch;
    int gzs[4];
    gzs[0] = c.yearGZ; gzs[1] = c.monthGZ; gzs[2] = c.dayGZ; gzs[3] = c.timeGZ;

    for (int i = 0; i < 5; ++i) c.wuXing[i] = 0;
    for (int i = 0; i < 4; ++i)
    {
        int b = branches[i];
        c.hideCount[i] = HIDE_N[b];
        for (int k = 0; k < c.hideCount[i]; ++k)
        {
            c.hideGan[i][k] = HIDE_GAN[b][k];
            c.shiShenZhi[i][k] = shiShenOf(c.dayStem, HIDE_GAN[b][k]);
        }
        for (int k = c.hideCount[i]; k < 4; ++k) { c.hideGan[i][k] = -1; c.shiShenZhi[i][k] = -1; }
        c.naYin[i] = gzs[i];
        c.xunKong[i][0] = 0; c.xunKong[i][1] = 0;
        int xun = gzs[i] / 10;                                  /* 旬：0=甲子旬 …… 5=甲寅旬 */
        c.xunKong[i][0] = ((10 - 2 * xun) % 12 + 12) % 12;
        c.xunKong[i][1] = (c.xunKong[i][0] + 1) % 12;
    }
    /* 五行统计：4 个天干 + 全部藏干 */
    c.wuXing[(c.yearGZ % 10) / 2]++;
    c.wuXing[monthStem / 2]++;
    c.wuXing[c.dayStem / 2]++;
    c.wuXing[c.timeStem / 2]++;
    for (int i = 0; i < 4; ++i)
        for (int k = 0; k < c.hideCount[i]; ++k)
            c.wuXing[c.hideGan[i][k] / 2]++;

    /* ---- 大运 ---- */
    c.hasYun = (gender == 0 || gender == 1);
    if (c.hasYun)
    {
        bool yangYear = (yearStem % 2 == 0);
        bool male = (gender == 1);
        c.forward = (yangYear && male) || (!yangYear && !male);

        Moment startM = c.forward ? Moment() : prev;   /* 顺行：从出生到下一个节 */
        Moment endM   = c.forward ? next : Moment();   /* 逆行：从上一个节到出生 */
        if (c.forward)
        {
            startM.y = y; startM.m = mo; startM.d = d; startM.h = h; startM.mi = mi; startM.s = 0;
            startM.t = birth;
        }
        else
        {
            endM.y = y; endM.m = mo; endM.d = d; endM.h = h; endM.mi = mi; endM.s = 0;
            endM.t = birth;
        }

        int endTZI = (endM.h == 23) ? 11 : timeZhiIndex(endM.h);
        int startTZI = (startM.h == 23) ? 11 : timeZhiIndex(startM.h);
        int hourDiff = endTZI - startTZI;
        int dayDiff = (int)(toJDN(endM.y, endM.m, endM.d) - toJDN(startM.y, startM.m, startM.d));
        if (hourDiff < 0) { hourDiff += 12; dayDiff -= 1; }

        int monthDiff = hourDiff * 10 / 30;
        int months = dayDiff * 4 + monthDiff;
        int days = hourDiff * 10 - monthDiff * 30;
        c.startYear = months / 12;
        c.startMonth = months % 12;
        c.startDay = days;
        c.startHour = 0;

        /* 起运日期 = 出生 + startYear 年 + startMonth 月 + startDay 天 */
        int sy = y + c.startYear, sm = mo, sd = d;
        if (sm == 2 && sd > 28 && !isLeapYear(sy)) sd = 28;      /* 2月29日 -> 28日 */
        sm += c.startMonth;
        while (sm > 12) { sm -= 12; ++sy; }
        int dim = daysInMonth(sy, sm);
        if (sd > dim) sd = dim;
        long jd2 = toJDN(sy, sm, sd) + c.startDay;
        fromJDN(jd2, sy, sm, sd);
        c.startSolarYear = sy;

        for (int i = 1; i <= 10; ++i)
        {
            int gz = c.monthGZ + (c.forward ? i : -i);
            gz = ((gz % 60) + 60) % 60;
            c.daYunGZ[i - 1] = gz;
            c.daYunAge[i - 1] = c.startSolarYear + (i - 1) * 10 - y + 1;
        }
    }
    return true;
}

/* ===================== 输出（GBK 对齐：汉字算 2 格） ===================== */
static int cellsOf(const string &s)
{
    int w = 0;
    for (size_t i = 0; i < s.size(); )
    {
        unsigned char ch = (unsigned char)s[i];
        if (ch < 0x80) { w += 1; i += 1; }
        else           { w += 2; i += 2; }
    }
    return w;
}

static string padTo(const string &s, int width)
{
    string r = s;
    for (int i = cellsOf(s); i < width; ++i) r += ' ';
    return r;
}

static string num2str(int v)
{
    ostringstream os;
    os << v;
    return os.str();
}

static string dateStr(int y, int m, int d)
{
    ostringstream os;
    os << y << "-" << (m < 10 ? "0" : "") << m << "-" << (d < 10 ? "0" : "") << d;
    return os.str();
}

static string jieStr(const Moment &j)
{
    ostringstream os;
    os << dateStr(j.y, j.m, j.d) << " "
       << (j.h < 10 ? "0" : "") << j.h << ":" << (j.mi < 10 ? "0" : "") << j.mi;
    return os.str();
}

/* 农历年中文：1990 -> 一九九〇 */
